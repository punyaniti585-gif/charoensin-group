export const menuDict: Partial<Record<LanguageCode, Phrases>> = { en, "zh-CN": zhCN, "zh-TW": zhTW, ja };

/** Leading menu numbering kept as-is: "01 ", "08.02 " */
const NUMBER_PREFIX = /^(\d+(?:\.\d+)?\s+)(.*)$/;

export function translateMenuLabel(label: string, lang: LanguageCode): string {
  if (lang === "th") return label;
  // menu table first, then the shared content phrases; chosen language → English
  const find = (key: string) =>
    menuDict[lang]?.[key] ?? phraseDict[lang]?.[key] ?? menuDict.en?.[key] ?? phraseDict.en?.[key];
  const whole = find(label);
  if (whole) return whole;
  const m = NUMBER_PREFIX.exec(label);
  const hit = m ? find(m[2]) : undefined;
  return m && hit ? m[1] + hit : label;
}

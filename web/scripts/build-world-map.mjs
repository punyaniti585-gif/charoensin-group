// Generates src/data/world-map.ts — real country outlines as pre-projected
// SVG paths (Natural Earth projection, 1000 × 520 viewBox).
//
//   node scripts/build-world-map.mjs
//
// Background: world-atlas 110m (light). The 10 Charoensin markets: 50m (crisper
// when the map zooms in). Run once and commit the output; the site ships no map
// libraries at runtime.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { feature, mesh } from "topojson-client";
import { geoNaturalEarth1, geoPath, geoBounds } from "d3-geo";

const require = createRequire(import.meta.url);
const world110 = require("world-atlas/countries-110m.json");
const land110 = require("world-atlas/land-110m.json");

const W = 1000;
const H = 520;

// ISO 3166 numeric ids (world-atlas) + main city used as the route endpoint
const MARKETS = [
  { code: "TH", id: "764", city: { th: "กรุงเทพฯ", en: "Bangkok", lon: 100.5, lat: 13.75 } },
  { code: "CN", id: "156", city: { th: "ปักกิ่ง", en: "Beijing", lon: 116.4, lat: 39.9 } },
  { code: "KR", id: "410", city: { th: "โซล", en: "Seoul", lon: 126.98, lat: 37.57 } },
  { code: "JP", id: "392", city: { th: "โตเกียว", en: "Tokyo", lon: 139.69, lat: 35.69 } },
  { code: "IN", id: "356", city: { th: "นิวเดลี", en: "New Delhi", lon: 77.21, lat: 28.61 } },
  { code: "AE", id: "784", city: { th: "อาบูดาบี", en: "Abu Dhabi", lon: 54.37, lat: 24.45 } },
  { code: "DE", id: "276", city: { th: "เบอร์ลิน", en: "Berlin", lon: 13.4, lat: 52.52 } },
  { code: "GB", id: "826", city: { th: "ลอนดอน", en: "London", lon: -0.13, lat: 51.51 } },
  { code: "US", id: "840", city: { th: "วอชิงตัน ดี.ซี.", en: "Washington, D.C.", lon: -77.04, lat: 38.91 } },
  { code: "AU", id: "036", city: { th: "แคนเบอร์รา", en: "Canberra", lon: 149.13, lat: -35.28 } },
];

const all110 = feature(world110, world110.objects.countries);
const noAntarctica = { type: "FeatureCollection", features: all110.features.filter((f) => f.id !== "010") };

const projection = geoNaturalEarth1().fitExtent(
  [
    [8, 8],
    [W - 8, H - 8],
  ],
  noAntarctica
);
const pathGen = geoPath(projection);
const round = (d) => d.replace(/(\d+\.\d)\d+/g, "$1");

// Land fill (all countries) and internal borders (one mesh, drawn once)
// Land (merged, no duplicate shared edges) without Antarctica
const landAll = feature(land110, land110.objects.land);
const landPolys = landAll.features.flatMap((f) =>
  f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates]
);
const land = round(
  pathGen({
    type: "MultiPolygon",
    coordinates: landPolys.filter((poly) => geoBounds({ type: "Polygon", coordinates: poly })[1][1] > -60),
  })
);
const borders = round(
  pathGen(mesh(world110, world110.objects.countries, (a, b) => a !== b && a.id !== "010" && b.id !== "010"))
);

const all50 = all110;
const markets = MARKETS.map((m) => {
  const f = all50.features.find((x) => x.id === m.id);
  if (!f) throw new Error(`country ${m.code} (${m.id}) not found`);
  // Mainland-only bounds for camera framing (ignore far-flung islands/territories)
  let geo = f;
  if (f.geometry.type === "MultiPolygon") {
    const polys = f.geometry.coordinates.map((c) => ({ type: "Feature", geometry: { type: "Polygon", coordinates: c } }));
    polys.sort((a, b) => pathGen.area(b) - pathGen.area(a));
    // keep polygons that are at least 3% of the largest (drops Alaska-scale outliers only when tiny)
    const big = pathGen.area(polys[0]);
    geo = { type: "FeatureCollection", features: polys.filter((p) => pathGen.area(p) >= big * 0.03) };
  }
  const [[x0, y0], [x1, y1]] = pathGen.bounds(m.code === "US" ? lower48(f) : geo);
  const [cx, cy] = projection([m.city.lon, m.city.lat]);
  return {
    code: m.code,
    d: round(pathGen(f)),
    bbox: [x0, y0, x1, y1].map((v) => +v.toFixed(1)),
    city: { ...m.city, x: +cx.toFixed(1), y: +cy.toFixed(1) },
  };
});

// Contiguous US only (frame the camera on the lower 48)
function lower48(f) {
  return {
    type: "Feature",
    geometry: {
      type: "MultiPolygon",
      coordinates: f.geometry.coordinates.filter((poly) => {
        const [[lon0, lat0], [lon1, lat1]] = geoBounds({ type: "Polygon", coordinates: poly });
        return lon0 > -130 && lat1 < 50 && lat0 > 23;
      }),
    },
  };
}

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-world-map.mjs — do not edit by hand.
// Source: world-atlas (Natural Earth, public domain) · projection: Natural Earth 1.

export const WORLD_VIEWBOX = { width: ${W}, height: ${H} } as const;

/** All countries (110m), one path — land fill */
export const WORLD_LAND = ${JSON.stringify(land)};

/** Internal country borders (110m), one path */
export const WORLD_BORDERS = ${JSON.stringify(borders)};

export interface MarketShape {
  code: string;
  /** Country outline (50m) */
  d: string;
  /** Mainland bounds [x0, y0, x1, y1] for camera framing */
  bbox: [number, number, number, number];
  /** Main city — route endpoint */
  city: { th: string; en: string; lon: number; lat: number; x: number; y: number };
}

export const MARKET_SHAPES: MarketShape[] = ${JSON.stringify(markets, null, 2)};
`;

const dest = path.resolve("src/data/world-map.ts");
fs.writeFileSync(dest, out);
console.log("wrote", dest, Math.round(out.length / 1024) + "KB");
